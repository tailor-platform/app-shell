// Only the gateway is scripted: validation, ui_render execution, message parts,
// renderer, streaming, and Stop all use the production AppShell code paths.
function createScriptedClient(): AIGatewayClient {
  return {
    async *streamChatCompletion({ messages, signal }) {
      const rendered = messages[messages.length - 1]?.role === "tool";
      const reply = rendered
        ? "The cards above are **read-only examples**. Review actual orders in your application's order page."
        : "I'll show a scripted report and an application-owned order summary.";
      for (const word of reply.split(" ")) {
        if (signal?.aborted) throw new DOMException("Aborted", "AbortError");
        await new Promise<void>((resolve, reject) => {
          const onAbort = () => {
            clearTimeout(timer);
            reject(new DOMException("Aborted", "AbortError"));
          };
          const timer = setTimeout(() => {
            signal?.removeEventListener("abort", onAbort);
            resolve();
          }, 60);
          signal?.addEventListener("abort", onAbort, { once: true });
        });
        yield { type: "text-delta", text: `${word} ` } satisfies AIChatCompletionEvent;
      }
      if (!rendered) {
        if (signal?.aborted) throw new DOMException("Aborted", "AbortError");
        yield {
          type: "tool-call",
          toolCallId: crypto.randomUUID(),
          toolName: "ui_render",
          argumentsText: JSON.stringify(DEMO_DOCUMENT),
        };
      }
      yield { type: "done" };
    },
  };
}

const SUGGESTIONS = ["Show an inbound report", "Display an order summary card"];

const AIChatDemoPage = () => {
  const client = useMemo(() => createScriptedClient(), []);
  const { messages, status, sendMessage, stop } = useAIChat({
    client,
    model: "demo-model",
    tools: { ui_render: ui.tool },
  });

  const retryLastQuestion = () => {
    const lastUserTurn = [...messages].reverse().find((message) => message.role === "user");
    if (lastUserTurn) void sendMessage(lastUserTurn.content);
  };

  return (
    <Layout fill>
      <Layout.Header title="AIChat Demo" />
      <Layout.Column>
        <p className="text-sm text-muted-foreground">
          Runs on scripted data — no model or live order API is called. The ui_render local tool
          displays a Report and a custom card, then the assistant continues.
        </p>
        {/* `overflow-hidden` keeps the header rule inside the card's rounded corners. */}
        <Card.Root className="flex min-h-0 flex-1 flex-col overflow-hidden">
          <AIChat status={status}>
            <AIChat.Header
              title="Assistant"
              actions={
                <AIChat.Action label="Clear conversation" onClick={() => window.location.reload()}>
                  <Eraser className="size-3.5" aria-hidden />
                </AIChat.Action>
              }
            />
            <AIChat.Conversation>
              {messages.length === 0 ? (
                <AIChat.EmptyState
                  icon={<Sparkles className="size-6 text-primary" aria-hidden />}
                  title="Ask the assistant"
                  description="Try the Report and custom-card renderer using scripted data."
                >
                  <AIChat.Suggestions>
                    {SUGGESTIONS.map((suggestion) => (
                      <AIChat.Suggestion
                        key={suggestion}
                        suggestion={suggestion}
                        onSelect={sendMessage}
                      />
                    ))}
                  </AIChat.Suggestions>
                </AIChat.EmptyState>
              ) : (
                messages.map((message) => (
                  <AIChat.Message key={message.id} from={message.role}>
                    {message.parts.map((part) => {
                      if (part.type === "text") {
                        return <AIChat.Response key={part.id}>{part.text}</AIChat.Response>;
                      }
                      return part.parts.map((displayPart, index) =>
                        displayPart.type === "generative-ui" ? (
                          <ui.Renderer key={`${part.id}:${index}`} document={displayPart.data} />
                        ) : null,
                      );
                    })}
                    {message.role === "assistant" && status === "ready" && message.content ? (
                      <AIChat.Actions className="-ml-1.5">
                        <AIChat.Action
                          label="Copy"
                          onClick={() => void navigator.clipboard?.writeText(message.content)}
                        >
                          <Copy className="size-3.5" aria-hidden />
                        </AIChat.Action>
                        <AIChat.Action label="Retry" onClick={retryLastQuestion}>
                          <RefreshCw className="size-3.5" aria-hidden />
                        </AIChat.Action>
                      </AIChat.Actions>
                    ) : null}
                  </AIChat.Message>
                ))
              )}
            </AIChat.Conversation>
            <AIChat.Composer
              onSubmit={(message) => sendMessage(message)}
              onStop={stop}
              actions={<Checkbox label="Search the knowledge base" />}
              placeholder="Ask about your orders…"
            />
          </AIChat>
        </Card.Root>
      </Layout.Column>
    </Layout>
  );
};

AIChatDemoPage.appShellPageProps = {
  meta: { title: "AIChat Demo" },
} satisfies AppShellPageProps;

export default AIChatDemoPage;
